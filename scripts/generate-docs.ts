import { mkdir, writeFile } from 'node:fs/promises';
import { Client, GatewayIntentBits } from 'discord.js';
import { applicationCommandData, createRegistry } from '../src/registry.js';
import { createPool } from '../src/db/pool.js';
import { logger } from '../src/logger.js';

const client = new Client({ intents: [GatewayIntentBits.Guilds] });
const pool = createPool('postgresql://localhost/metadata_only');
try {
  // Factories only construct handlers; neither gateway nor database is opened to generate documentation.
  const registry = createRegistry({ client, pool, prefixes: new Map(), ownerIds: new Set(), logger, startedAt: Date.now(), env: {} });
  const sections = ['# Command reference', '', 'Generated by `npm run generate-docs` from the command registry.', '', '## Prefix commands', ''];
  for (const command of registry.prefix) sections.push(`### ${command.name}`, '', command.description,
    ...(command.usage?.length ? ['', ...command.usage.map(usage => `- ${usage}`)] : []),
    ...(command.ownerOnly ? ['', 'Bot owner only.'] : []), '');
  sections.push('## Application commands', '');
  for (const command of applicationCommandData) {
    sections.push(`### ${command.type && command.type !== 1 ? 'Context: ' : '/'}${command.name}`, '', ('description' in command && command.description) || 'Context menu command.', '');
    if ('options' in command && command.options?.length) sections.push(...command.options.map(option => '- `' + option.name + '`: ' + option.description), '');
  }
  await mkdir('docs', { recursive: true });
  await writeFile('docs/commandList.md', `${sections.join('\n').trimEnd()}\n`);
} finally { await client.destroy(); await pool.end(); }
